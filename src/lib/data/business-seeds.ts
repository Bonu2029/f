export interface ServiceSeed {
  name: string;
  minutes: number;
  price: number; // dollars
  description: string;
  /** Category slug override; defaults to the business's primary category. */
  category?: string;
  deposit?: number;
  buffer?: number;
}

export interface StaffSeed {
  name: string;
  role: string;
  rating: number;
  reviews: number;
  bio: string;
  /** Indexes into the business's `services` array. Omit = performs all. */
  services?: number[];
}

export interface ReviewSeed {
  author: string;
  rating: 1 | 2 | 3 | 4 | 5;
  daysAgo: number;
  body: string;
  staffIndex?: number;
  serviceIndex?: number;
  photos?: number;
  reply?: string;
}

export interface BusinessSeed {
  slug: string;
  name: string;
  tagline: string;
  about: string;
  category: string;
  extraCategories?: string[];
  neighborhood: string;
  address: string;
  postal: string;
  lat: number;
  lng: number;
  phone: string;
  email: string;
  website?: string;
  rating: number;
  reviewCount: number;
  priceLevel: 1 | 2 | 3;
  verified: boolean;
  pro?: boolean;
  parking?: string;
  /** [opens, closes] per day, index 0 = Sunday. null = closed. */
  hours: ([string, string] | null)[];
  services: ServiceSeed[];
  staff: StaffSeed[];
  reviews: ReviewSeed[];
  freeCancellationHours?: number;
}

